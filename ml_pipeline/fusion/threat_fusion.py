import time
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional, Set, Tuple

from shared.logging.logger import get_logger
from ml_pipeline.schema.predictions import StandardDetectionPrediction, StandardModelPrediction
from ml_pipeline.taxonomy.taxonomy_manager import TaxonomyManager, get_taxonomy_manager

log = get_logger("ml_pipeline.fusion")


@dataclass
class CorrelatedEvidence:
    """Individual piece of evidence contributing to a threat assessment."""
    source_model: str
    modality: str
    class_id: str
    confidence: float
    timestamp_ms: int
    raw_label: str
    bounding_box: Optional[List[int]] = None
    is_shadow: bool = False


@dataclass
class FusedThreatAssessment:
    """Consolidated assessment generated by multi-modal evidence fusion."""
    assessment_id: str
    timestamp_iso: str
    threat_tier: int                        # Tier 0 (None), Tier 1 (Nuisance/Animal), Tier 2 (Lethal/Weapon)
    threat_category: str                    # "weapon", "audio", "animal", "hazard", "multimodal"
    primary_class_id: str
    confidence: float
    evidence: List[CorrelatedEvidence]
    is_cross_modal: bool                    # True if both visual + acoustic evidence correlated
    is_shadow_only: bool                    # True if driven exclusively by shadow/experimental models
    recommended_actions: List[str]
    reasoning: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class ThreatFusionEngine:
    """
    Fuses asynchronous visual, acoustic, and sensor predictions into actionable safety decisions.
    Preserves raw model outputs while producing correlated multi-modal assessments.
    """

    def __init__(
        self,
        temporal_window_sec: float = 3.0,
        iou_duplicate_threshold: float = 0.50,
        taxonomy: Optional[TaxonomyManager] = None,
    ):
        self.window_sec = temporal_window_sec
        self.iou_threshold = iou_duplicate_threshold
        self.taxonomy = taxonomy or get_taxonomy_manager()
        self._recent_evidence: List[CorrelatedEvidence] = []

    def ingest_predictions(
        self,
        predictions: List[StandardModelPrediction],
        current_time_ms: Optional[int] = None,
    ) -> List[FusedThreatAssessment]:
        """
        Ingest batch of model predictions, correlate with recent evidence, and produce assessments.
        """
        now_ms = current_time_ms if current_time_ms is not None else int(time.time() * 1000)
        self._prune_expired_evidence(now_ms)

        # 1. Ingest raw predictions into evidence store without overwriting
        for model_pred in predictions:
            is_shadow = model_pred.metadata.get("execution_mode") == "shadow"
            for det in model_pred.predictions:
                evidence = CorrelatedEvidence(
                    source_model=model_pred.model_id,
                    modality=model_pred.modality,
                    class_id=det.class_id,
                    confidence=det.confidence,
                    timestamp_ms=now_ms,
                    raw_label=det.raw_label,
                    bounding_box=det.bounding_box,
                    is_shadow=is_shadow,
                )
                self._recent_evidence.append(evidence)

        # 2. Correlate cross-modal evidence (e.g. Visual Firearm + Acoustic Gunshot)
        assessments = self._fuse_evidence(now_ms)
        return assessments

    def _prune_expired_evidence(self, now_ms: int) -> None:
        cutoff = now_ms - int(self.window_sec * 1000)
        self._recent_evidence = [e for e in self._recent_evidence if e.timestamp_ms >= cutoff]

    def _fuse_evidence(self, now_ms: int) -> List[FusedThreatAssessment]:
        assessments: List[FusedThreatAssessment] = []
        if not self._recent_evidence:
            return assessments

        # Group evidence by taxonomy domain
        visual_weapons = [e for e in self._recent_evidence if e.class_id.startswith("weapon.")]
        acoustic_threats = [e for e in self._recent_evidence if e.class_id.startswith("audio.threat.")]
        animals = [e for e in self._recent_evidence if e.class_id.startswith("animal.")]

        # Case A: Multimodal Cross-Correlation (Visual Firearm + Acoustic Gunshot)
        if visual_weapons and acoustic_threats:
            vw = max(visual_weapons, key=lambda x: x.confidence)
            at = max(acoustic_threats, key=lambda x: x.confidence)

            # Combined confidence using Noisy-OR probability fusion
            fused_conf = 1.0 - ((1.0 - vw.confidence) * (1.0 - at.confidence))
            fused_conf = min(0.99, round(fused_conf, 4))

            is_shadow = vw.is_shadow and at.is_shadow
            actions = ["cloud_alert", "telegram_alert", "strobe"]
            if not is_shadow:
                actions.append("siren")

            assessments.append(
                FusedThreatAssessment(
                    assessment_id=f"fused-mm-{now_ms}",
                    timestamp_iso=datetime.now(timezone.utc).isoformat(),
                    threat_tier=2,
                    threat_category="multimodal",
                    primary_class_id="weapon.firearm.handgun",
                    confidence=fused_conf,
                    evidence=[vw, at],
                    is_cross_modal=True,
                    is_shadow_only=is_shadow,
                    recommended_actions=actions,
                    reasoning=f"High-confidence cross-modal correlation: Visual {vw.raw_label} ({vw.confidence:.2f}) confirmed by acoustic {at.raw_label} ({at.confidence:.2f}).",
                )
            )

        # Case B: Visual Weapon Isolated
        elif visual_weapons:
            # Deduplicate bounding boxes within same frame/class
            deduped = self._deduplicate_visual(visual_weapons)
            for vw in deduped:
                actions = ["cloud_alert", "telegram_alert", "strobe"]
                if not vw.is_shadow:
                    actions.append("siren")

                assessments.append(
                    FusedThreatAssessment(
                        assessment_id=f"fused-vis-{now_ms}-{vw.class_id}",
                        timestamp_iso=datetime.now(timezone.utc).isoformat(),
                        threat_tier=2,
                        threat_category="weapon",
                        primary_class_id=vw.class_id,
                        confidence=vw.confidence,
                        evidence=[vw],
                        is_cross_modal=False,
                        is_shadow_only=vw.is_shadow,
                        recommended_actions=actions,
                        reasoning=f"Visual detection of {vw.raw_label} with confidence {vw.confidence:.2f}.",
                    )
                )

        # Case C: Acoustic Threat Isolated
        elif acoustic_threats:
            at = max(acoustic_threats, key=lambda x: x.confidence)
            assessments.append(
                FusedThreatAssessment(
                    assessment_id=f"fused-audio-{now_ms}",
                    timestamp_iso=datetime.now(timezone.utc).isoformat(),
                    threat_tier=2 if "gunshot" in at.class_id else 1,
                    threat_category="audio",
                    primary_class_id=at.class_id,
                    confidence=at.confidence,
                    evidence=[at],
                    is_cross_modal=False,
                    is_shadow_only=at.is_shadow,
                    recommended_actions=["cloud_alert", "telegram_alert", "visual_cue"],
                    reasoning=f"Acoustic signature detected: {at.raw_label} with confidence {at.confidence:.2f}.",
                )
            )

        # Case D: Animal Detection (Non-lethal Tier 1 / Nuisance)
        elif animals:
            an = max(animals, key=lambda x: x.confidence)
            is_predator = "predator" in an.class_id
            assessments.append(
                FusedThreatAssessment(
                    assessment_id=f"fused-animal-{now_ms}",
                    timestamp_iso=datetime.now(timezone.utc).isoformat(),
                    threat_tier=1 if is_predator else 0,
                    threat_category="animal",
                    primary_class_id=an.class_id,
                    confidence=an.confidence,
                    evidence=[an],
                    is_cross_modal=False,
                    is_shadow_only=an.is_shadow,
                    recommended_actions=["cloud_alert", "telegram_alert"] if is_predator else ["log_only"],
                    reasoning=f"Animal observed: {an.raw_label} ({an.confidence:.2f}). Passive fauna presence does not trigger audible deterrence.",
                )
            )

        return assessments

    def _deduplicate_visual(self, evidence_list: List[CorrelatedEvidence]) -> List[CorrelatedEvidence]:
        """Simple Non-Maximum Suppression for multi-model visual overlap."""
        if len(evidence_list) <= 1:
            return evidence_list

        sorted_evidence = sorted(evidence_list, key=lambda x: x.confidence, reverse=True)
        selected: List[CorrelatedEvidence] = []

        for cand in sorted_evidence:
            if cand.bounding_box is None:
                selected.append(cand)
                continue

            overlap = False
            for prev in selected:
                if prev.bounding_box and self._compute_iou(cand.bounding_box, prev.bounding_box) > self.iou_threshold:
                    overlap = True
                    break

            if not overlap:
                selected.append(cand)

        return selected

    def _compute_iou(self, boxA: List[int], boxB: List[int]) -> float:
        xA = max(boxA[0], boxB[0])
        yA = max(boxA[1], boxB[1])
        xB = min(boxA[2], boxB[2])
        yB = min(boxA[3], boxB[3])

        interArea = max(0, xB - xA) * max(0, yB - yA)
        boxAArea = (boxA[2] - boxA[0]) * (boxA[3] - boxA[1])
        boxBArea = (boxB[2] - boxB[0]) * (boxB[3] - boxB[1])
        iou = interArea / float(boxAArea + boxBArea - interArea + 1e-6)
        return float(iou)
